import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { format, resolveConfig } from "prettier";
import { buildExtendedCatalog, parseConstituents, publicAssetSchema } from "./catalog.js";
import type { LogoPalette, PublicCatalogAsset } from "./catalog.js";
import { logoColor } from "./catalog-color.js";
import { NEUTRAL_ASSET_COLOR } from "@stock-arena/game-core";

const root = fileURLToPath(new URL("../../..", import.meta.url)),
  directory = resolve(root, "packages/game-core/data/sp500");
const manifestSchema = z.object({
  asOf: z.string().regex(/^\d{4}-\d{2}-\d{2}$/),
  constituentRevision: z.string().regex(/^[a-f0-9]{40}$/),
});
const manifest = manifestSchema.parse(
  JSON.parse(await readFile(resolve(directory, "manifest.json"), "utf8")),
);
const csvPath = resolve(directory, `constituents-${manifest.asOf}.csv`),
  assetsPath = resolve(directory, `xstocks-${manifest.asOf}.json`),
  colorsPath = resolve(directory, "logo-colors.json");
async function request(url: string) {
  for (let attempt = 0; attempt < 3; attempt++) {
    const response = await fetch(url, { signal: AbortSignal.timeout(15000), redirect: "error" });
    if (response.ok) return response;
    if (response.status !== 429 && response.status < 500)
      throw new Error("Public catalog source unavailable.");
    const retry = Number(response.headers.get("retry-after"));
    await new Promise((r) =>
      setTimeout(r, Math.max(1000 * 2 ** attempt, Number.isFinite(retry) ? retry * 1000 : 0)),
    );
  }
  throw new Error("Public catalog retries exhausted.");
}
if (process.argv.includes("--refresh")) {
  const csv = await (
    await request(
      `https://raw.githubusercontent.com/datasets/s-and-p-500-companies/${manifest.constituentRevision}/data/constituents.csv`,
    )
  ).text();
  parseConstituents(csv);
  await writeFile(csvPath, csv);
  const nodes: PublicCatalogAsset[] = [];
  for (let page = 1; page <= 20; page++) {
    const data = z
      .object({
        nodes: z.array(publicAssetSchema),
        page: z.object({ currentPage: z.number(), hasNextPage: z.boolean() }),
      })
      .parse(
        await (
          await request(`https://api.backed.fi/api/v2/public/assets?page=${page}&pageSize=100`)
        ).json(),
      );
    if (data.page.currentPage !== page) throw new Error("Catalog pagination did not advance.");
    nodes.push(
      ...data.nodes.map((n) => ({
        ...n,
        deployments: n.deployments.filter((d) => d.network.toLowerCase() === "mantle"),
      })),
    );
    if (!data.page.hasNextPage) break;
    if (page === 20) throw new Error("Catalog pagination limit exceeded.");
  }
  await writeFile(assetsPath, JSON.stringify(nodes, null, 2) + "\n");
}
const csv = await readFile(csvPath, "utf8"),
  nodes = z.array(publicAssetSchema).parse(JSON.parse(await readFile(assetsPath, "utf8"))),
  constituents = parseConstituents(csv);
let palette: LogoPalette = {};
try {
  palette = JSON.parse(await readFile(colorsPath, "utf8")) as LogoPalette;
} catch {
  /* First refresh creates the cache. */
}
const catalog = buildExtendedCatalog(constituents, nodes, palette);
if (process.argv.includes("--refresh"))
  for (const [ticker, asset] of Object.entries(catalog)) {
    if (palette[ticker]?.logo === asset.logo && !process.argv.includes("--refresh-logos")) continue;
    try {
      const response = await request(asset.logo),
        length = Number(response.headers.get("content-length"));
      if (length > 1024 * 1024) throw new Error("Logo exceeds size limit.");
      const bytes = new Uint8Array(await response.arrayBuffer());
      palette[ticker] = {
        logo: asset.logo,
        color: logoColor(bytes),
        sha256: createHash("sha256").update(bytes).digest("hex"),
      };
    } catch {
      palette[ticker] = { logo: asset.logo, color: NEUTRAL_ASSET_COLOR };
    }
  }
const final = buildExtendedCatalog(constituents, nodes, palette),
  version = `sp500-xstocks-${manifest.asOf}-${createHash("sha256").update(JSON.stringify(final)).digest("hex").slice(0, 12)}`;
await writeFile(colorsPath, JSON.stringify(palette, null, 2) + "\n");
const source = `/** Generated by pnpm catalog:generate. Public inputs and attribution: data/sp500. */\nimport type { ReferenceCatalog } from "../assets.js";\nexport const EXTENDED_CATALOG_VERSION = ${JSON.stringify(version)};\nexport const EXTENDED_CATALOG_METADATA = ${JSON.stringify({ ...manifest, constituents: constituents.size, availableAssets: nodes.length, matchedStocks: Object.keys(final).length }, null, 2)};\nexport const EXTENDED_ASSETS: ReferenceCatalog = ${JSON.stringify(final, null, 2)};\n`;
await mkdir(resolve(root, "packages/game-core/src/catalog"), { recursive: true });
await writeFile(
  resolve(root, "packages/game-core/src/catalog/extended.generated.ts"),
  await format(source, { ...(await resolveConfig(root)), parser: "typescript" }),
);
console.info(
  `Catalog generated: ${Object.keys(final).length} stocks; ${constituents.size} constituent entries; ${manifest.asOf}.`,
);
